package accessmodifiers;

public class AccessModifiers {
	
/*
	
Class Level

| Access Modifier | Syntax Example      | Accessibility                                  |
|-----------------|---------------------|-----------------------------------------------|
| public          | public class A      | Access from anywhere                           |
| default         | class A             | Access within same package                    |
| private         | Not allowed         | Not allowed for top-level class               |
| protected       | Not allowed         | Not allowed for top-level class               |



Method Level

| Access Modifier | Syntax Example        | Accessibility                                                    |
|-----------------|-----------------------|-----------------------------------------------------------------|
| public          | public void m1()      | Access from anywhere                                            |
| default         | void m1()             | Access within same package                                     |
| private         | private void m1()     | Access only within same class                                  |
| protected       | protected void m1()   | Same package + outside package through child class             |


Variable Level

| Access Modifier | Syntax Example        | Accessibility                                                    |
|-----------------|-----------------------|-----------------------------------------------------------------|
| public          | public int a;         | Access from anywhere                                            |
| default         | int a;                | Access within same package                                     |
| private         | private int a;        | Access only within same class                                  |
| protected       | protected int a;      | Same package + outside package through child class             |


*/
	

}
