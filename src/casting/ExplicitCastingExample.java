package casting;

public class ExplicitCastingExample {
	
	
	public static void main(String[]args)
	{
		
		double a = 10.75;      
		int b = (int)a;   
		
		System.out.println("Double value: " + a);
        System.out.println("Integer value: " + b);
		
			
		
	}
		

}

/*
Explanation:

🔹 Explicit Type Casting

Explicit Casting → Converting a higher data type to a lower data type manually using casting syntax, which may cause data loss.



*/